function normalizeArabic(value: string) {
  return value
    .trim()
    .replace(/[\u064B-\u0652]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي");
}

const NORMALIZED_EXACT = Object.fromEntries(
  Object.entries(EXACT_ICONS).map(([name, icon]) => [normalizeArabic(name), icon]),
);

const SORTED_KEYWORDS = [...KEYWORD_ICONS]
  .map(([hint, icon]) => [normalizeArabic(hint), icon] as [string, string])
  .sort((left, right) => right[0].length - left[0].length);

export function matchCategoryIcon(name: string) {
  const trimmed = normalizeArabic(name);

  if (!trimmed) {
    return null;
  }

  const exact = NORMALIZED_EXACT[trimmed];

  if (exact) {
    return exact;
  }

  const keyword = SORTED_KEYWORDS.find(([hint]) => trimmed.includes(hint));

  if (keyword) {
    return keyword[1];
  }

  if (trimmed.startsWith("إيراد") || trimmed.startsWith("ايراد")) {
    return "📥";
  }

  return null;
}

export function isGenericCategoryIcon(icon: string | null | undefined) {
  return !icon || icon === "📦" || icon === "❓" || icon === "⭐";
}
